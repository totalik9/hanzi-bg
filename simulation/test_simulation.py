"""
Self-checks for the simulation harness itself.

A simulation that reports "17/20 students reach A2" is only worth as much as
the correctness of the model underneath it. These checks verify the parts
that can be verified independently:

  1. The Python scheduler port matches the Kotlin vectors generated by
     simulation/make_vectors.py (the same vectors the Kotlin unit test
     asserts against).
  2. The scheduler actually graduates cards (no infinite learning-step loop).
  3. Interval growth is monotonic and capped.
  4. The student profiles are actually distinct (a simulation where all 20
     students behave identically proves nothing).
  5. The content loader refuses to invent data when content.db is missing.
"""

import json
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import srs  # noqa: E402
import simulate_learners as sim  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent

PASS = "\033[32mPASS\033[0m"
FAIL = "\033[31mFAIL\033[0m"
failures = []


def check(name, condition, detail=""):
    if condition:
        print(f"  {PASS}  {name}")
    else:
        print(f"  {FAIL}  {name}  {detail}")
        failures.append(name)


def test_parity_with_kotlin_vectors():
    print("\n1. Python port vs Kotlin vectors")
    expected_path = ROOT / "simulation" / "expected_vectors.json"
    if not expected_path.exists():
        check("expected_vectors.json exists", False, str(expected_path))
        return
    expected = json.loads(expected_path.read_text(encoding="utf-8"))

    mismatches = 0
    checked = 0
    for name, steps in expected.items():
        state = None
        for step in steps:
            state = srs.schedule(state, step["rating"], step["now"])
            checked += 1
            if abs(state.stability - step["stability"]) > 1e-9 or \
               abs(state.difficulty - step["difficulty"]) > 1e-9 or \
               state.due_at != step["dueAt"] or \
               state.reps != step["reps"] or \
               state.lapses != step["lapses"] or \
               state.state != step["state"]:
                mismatches += 1
                print(f"     mismatch in {name}: {step['rating']}")
    check(f"all {checked} steps match the Kotlin vectors", mismatches == 0,
          f"{mismatches} mismatches")


def test_graduation():
    print("\n2. Scheduler state machine")
    state = srs.schedule(None, srs.GOOD, 0)
    check("new card starts in LEARNING", state.state == srs.STATE_LEARNING)
    state = srs.schedule(state, srs.GOOD, 600_000)
    check("graduates to REVIEW after 2 successes",
          state.state == srs.STATE_REVIEW, f"state={state.state}")

    # A card that always fails must never graduate.
    state = srs.schedule(None, srs.AGAIN, 0)
    stuck = True
    for i in range(20):
        state = srs.schedule(state, srs.AGAIN, 600_000 * (i + 1))
        if state.state == srs.STATE_REVIEW:
            stuck = False
            break
    check("a card that always fails never graduates", stuck)

    # Relearning graduates on a single success.
    state = srs.schedule(None, srs.AGAIN, 0)
    state = srs.schedule(state, srs.GOOD, 600_000)
    check("RELEARNING graduates on one success",
          state.state == srs.STATE_REVIEW, f"state={state.state}")


def test_interval_growth():
    print("\n3. Interval behaviour")
    # The interval is due_at - now. Comparing absolute due_at would be wrong:
    # it accumulates across reviews and is not the interval.
    state = srs.schedule(None, srs.GOOD, 0)
    now = 0
    intervals = []
    for _ in range(15):
        state = srs.schedule(state, srs.GOOD, now)
        intervals.append(state.due_at - now)
        now = state.due_at
    check("interval never shrinks",
          all(b >= a for a, b in zip(intervals, intervals[1:])))
    check("interval stays under one year",
          max(intervals) <= 365 * 86_400_000,
          f"max={max(intervals) / 86_400_000:.1f} days")


def test_profiles_are_distinct():
    print("\n4. Student profiles")
    students = sim.build_students()
    check("there are exactly 20 students", len(students) == 20, str(len(students)))

    minutes = {s.daily_minutes for s in students}
    retentions = {round(s.retention, 3) for s in students}
    consistencies = {round(s.consistency, 3) for s in students}
    check("daily_minutes vary", len(minutes) >= 8, f"{len(minutes)} distinct")
    check("retention varies", len(retentions) >= 8, f"{len(retentions)} distinct")
    check("consistency varies", len(consistencies) >= 8, f"{len(consistencies)} distinct")

    signatures = {
        (s.daily_minutes, s.retention, s.consistency, s.new_words_per_day,
         s.minutes_per_new_card, s.forget_rate)
        for s in students
    }
    check("no two students share a full behavioural signature",
          len(signatures) == len(students), f"{len(signatures)} unique")

    ages = {s.age for s in students}
    check("ages span a realistic range", len(ages) >= 8, f"{sorted(ages)}")

    # No student may be able to reach A2 vocabulary without doing any work.
    check("every student has a non-zero daily budget",
          all(s.daily_minutes > 0 for s in students))
    check("every student has a positive retention rate",
          all(0 < s.retention <= 1 for s in students))


def test_content_loader_refuses_to_invent():
    print("\n5. Content loader honesty")
    # The loader prefers content.db and falls back to the pipeline's
    # intermediate JSON. It must fail loudly when NEITHER is available --
    # that is the only way it could end up inventing numbers.
    missing = Path(tempfile.gettempdir()) / "definitely_missing_content"
    saved = (
        sim.CONTENT_DB,
        sim.VOCAB_JSON,
        sim.GRAMMAR_JSON,
        sim.SENTENCES_JSON,
        sim.BG_GLOSS_JSON,
    )
    try:
        sim.CONTENT_DB = missing / "content.db"
        sim.VOCAB_JSON = missing / "vocab_hsk.json"
        sim.GRAMMAR_JSON = missing / "grammar.json"
        sim.SENTENCES_JSON = missing / "sentences.json"
        sim.BG_GLOSS_JSON = missing / "bg_zh_wiktionary.json"
        try:
            sim.load_content()
            check("load_content() fails loudly when no content source exists",
                  False, "it returned instead of raising")
        except SystemExit as e:
            check("load_content() fails loudly when no content source exists",
                  "refuses to invent" in str(e))
    finally:
        (sim.CONTENT_DB, sim.VOCAB_JSON, sim.GRAMMAR_JSON,
         sim.SENTENCES_JSON, sim.BG_GLOSS_JSON) = saved


def test_simulation_runs_and_is_deterministic():
    print("\n6. Simulation determinism")
    if not sim.CONTENT_DB.exists():
        print("  (skipped: content.db not built yet)")
        return
    content = sim.load_content()
    import random
    a = [sim.simulate(s, content, random.Random(42)) for s in sim.build_students()]
    b = [sim.simulate(s, content, random.Random(42)) for s in sim.build_students()]
    same = all(x.words_solid == y.words_solid for x, y in zip(a, b))
    check("same seed produces identical results", same)

    # A student with a huge budget must learn more than one with almost none.
    generous = next(s for s in sim.build_students() if s.daily_minutes >= 45)
    scarce = next(s for s in sim.build_students() if s.daily_minutes <= 10)
    rg = random.Random(7)
    r_gen = sim.simulate(generous, content, rg)
    r_sca = sim.simulate(scarce, content, random.Random(7))
    check("more time -> more vocabulary",
          r_gen.words_solid > r_sca.words_solid,
          f"{r_gen.words_solid} vs {r_sca.words_solid}")


def main():
    print("=" * 70)
    print("Simulation harness self-checks")
    print("=" * 70)
    test_parity_with_kotlin_vectors()
    test_graduation()
    test_interval_growth()
    test_profiles_are_distinct()
    test_content_loader_refuses_to_invent()
    test_simulation_runs_and_is_deterministic()

    print()
    if failures:
        print(f"{len(failures)} CHECK(S) FAILED: {failures}")
        return 1
    print("All simulation harness checks passed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
