package bg.hanzi.learn.data.srs

import kotlinx.serialization.json.double
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import kotlinx.serialization.json.long
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File

/**
 * Proves the Kotlin SrsScheduler and the Python port in simulation/srs.py
 * behave identically.
 *
 * The A2 feasibility simulation models the APP. If this port ever drifts
 * from the real scheduler, the simulation would answer a question about a
 * different app than the one that ships. The test vectors are generated by
 * simulation/make_vectors.py.
 */
class SrsSchedulerParityTest {

    private data class Step(
        val rating: String,
        val now: Long,
        val dueAt: Long,
        val stability: Double,
        val difficulty: Double,
        val reps: Int,
        val lapses: Int,
        val state: Int,
    )

    private fun loadSteps(): Map<String, List<Step>> {
        val file = File("src/test/resources/srs_vectors.json")
        assertEquals("test vectors must exist", true, file.exists())
        val text = file.readText()
        val root = kotlinx.serialization.json.Json.parseToJsonElement(text).jsonObject

        return root.mapValues { (_, seq) ->
            seq.jsonObject.getValue("steps").jsonArray.map { step ->
                val o = step.jsonObject
                Step(
                    rating = o.getValue("rating").jsonPrimitive.content,
                    now = o.getValue("now").jsonPrimitive.long,
                    dueAt = o.getValue("dueAt").jsonPrimitive.long,
                    stability = o.getValue("stability").jsonPrimitive.double,
                    difficulty = o.getValue("difficulty").jsonPrimitive.double,
                    reps = o.getValue("reps").jsonPrimitive.int,
                    lapses = o.getValue("lapses").jsonPrimitive.int,
                    state = o.getValue("state").jsonPrimitive.int,
                )
            }
        }
    }

    @Test
    fun matchesPythonPort() {
        val vectors = loadSteps()
        assertEquals("expected 8 sequences", 8, vectors.size)

        var checked = 0
        vectors.forEach { (name, steps) ->
            var state: SrsState? = null
            steps.forEach { step ->
                val rating = Rating.valueOf(step.rating)
                state = SrsScheduler.schedule(state, rating, step.now)

                val actual = state!!
                assertEquals(
                    "$name: dueAt after ${step.rating}",
                    step.dueAt,
                    actual.dueAt,
                )
                assertEquals(
                    "$name: stability after ${step.rating}",
                    step.stability,
                    actual.stability,
                    1e-9,
                )
                assertEquals(
                    "$name: difficulty after ${step.rating}",
                    step.difficulty,
                    actual.difficulty,
                    1e-9,
                )
                assertEquals("$name: reps", step.reps, actual.reps)
                assertEquals("$name: lapses", step.lapses, actual.lapses)
                assertEquals("$name: state", step.state, actual.state)
                checked++
            }
        }
        assertEquals("expected 60 steps", 60, checked)
    }

    @Test
    fun cardGraduatesOutOfLearningAfterTwoSuccesses() {
        // Regression guard: without a graduation rule a card stays on the
        // 10-minute learning step forever and the review load grows without
        // bound.
        var state = SrsScheduler.schedule(null, Rating.GOOD, 0L)
        assertEquals(SrsScheduler.STATE_LEARNING, state.state)

        state = SrsScheduler.schedule(state, Rating.GOOD, 0L + 600_000L)
        assertEquals(
            "must graduate to REVIEW after 2 successes",
            SrsScheduler.STATE_REVIEW,
            state.state,
        )
    }

    @Test
    fun repeatedFailureStaysInLearning() {
        var state = SrsScheduler.schedule(null, Rating.AGAIN, 0L)
        assertEquals(SrsScheduler.STATE_RELEARNING, state.state)
        state = SrsScheduler.schedule(state, Rating.AGAIN, 600_000L)
        assertEquals(SrsScheduler.STATE_RELEARNING, state.state)
        state = SrsScheduler.schedule(state, Rating.GOOD, 1_200_000L)
        assertEquals(SrsScheduler.STATE_REVIEW, state.state)
    }

    @Test
    fun intervalGrowsAndIsCapped() {
        // The interval is dueAt - now. Absolute dueAt accumulates across
        // reviews and is NOT the interval.
        var state = SrsScheduler.schedule(null, Rating.GOOD, 0L)
        var now = 0L
        var previousInterval = 0L
        repeat(15) {
            state = SrsScheduler.schedule(state, Rating.GOOD, now)
            val interval = state.dueAt - now
            assertTrue("interval must not shrink", interval >= previousInterval)
            assertTrue(
                "interval must stay under one year",
                interval <= 365L * 24 * 60 * 60 * 1000,
            )
            previousInterval = interval
            now = state.dueAt
        }
    }
}
